public class ActStampaCumulo extends ActionSiap implements ICostantiCumulo {
	// [FT] - 03/08/2016 - MAC_LOG - Dichiaro un'istanza di Logger per SIESLog
	private static Logger siesLogger = Logger.getLogger(LogF3B.SIES_LOG);

	public String processRequest() throws F3BException {
		FascicoloSiepModel lFascicoloModel = (FascicoloSiepModel) getSessionAttribute("fascicolo");
		UtenteModel lUtenteMod = this.getUtenteConnesso();
		UfficioModel lUff = this.getUfficioUtenteConnesso();

		String lId = getRequestStringParameter(ICostantiEvento.CAMPO_ID_EVENTO);
		String lFlagTemplate = getRequestStringParameter("flagStampa");

		IEvento lCtrl = SICOLookupRemote.getEventoRemote();
		EventoModel lEventoModel = lCtrl.ExRicercaEventoByKey(new BigDecimal(lId));

		// String lMotivo = lEventoModel.getCodMotivo();
		EventoNotificaModel lEveMod = new EventoNotificaModel();

		lEveMod.getEvento().setIdEvento(new BigDecimal(lId));
		lEveMod.getEvento().setFasSieIdFascicoloSiep(lFascicoloModel.getIdFascicoloSiep());

		lEveMod.getEvento().setDescrLuogoEmittente(lUff.getDescrComune());
		lEveMod.getEvento().setDescrUfficioEmittente(lUff.getDescrTipoUfficio());

		lEveMod.getEvento().setDataAggiornamento(DateUtils.getSysDate());
		lEveMod.getEvento().setCodUfficioAggiornamento(lUff.getCodUfficio());
		lEveMod.getEvento().setCodOperatoreAggiornamento(this.getCodUtenteConnesso());
		lEveMod.getEvento().setFlagDocumentoRegistrato("N");

		ITemplate lCtrlTem = SICOLookupRemote.getTemplateRemote();
		TemplateModel lTemMod = new TemplateModel();
		lTemMod = lCtrlTem.ExRicercaTemplateByTipEveTipoProvCodMotivoFlagTemplate("01", "04",
				lEventoModel.getCodMotivo(), lFlagTemplate);
		lEveMod.setNomeTemplate(lTemMod.getIdTemplate());

		ICumulo lCtrlCumulo = SIEPLookupRemote.getCumuloRemote();
		ByteArrayOutputStream lReport = lCtrlCumulo.ExStampaDocumentoXCumulo(lEveMod, lUtenteMod); // setta la
																									// risposta
																									// nella
																									// request

		// Prepara la pagina di destinazione
		setRequestAttribute("report", lReport);

		if (lReport != null) {
			// [FT] - 03/08/2016 - MAC_LOG - Utilizzo la variabile di istanza siesLogger al posto di
			// LogF3B.getLogger()
			siesLogger.info("Report del Cumulo SIZE = " + lReport.size());
		}
		return IWebConstants.PG_DOWNLOAD;
	}
}